import 'package:pro_image_editor/pro_image_editor.dart';

import '../l10n/app_localizations.dart';

/// Maps [AppLocalizations] keys to [I18n] for the pro_image_editor.
/// Omitted fields use the editor's English defaults.
I18n buildEditorI18n(AppLocalizations l10n) => I18n(
      cancel: l10n.cancel,
      done: l10n.done,
      undo: l10n.undo,
      redo: l10n.redo,
      remove: l10n.remove,
      various: I18nVarious(
        closeEditorWarningTitle: l10n.closeEditorWarningTitle,
        closeEditorWarningMessage: l10n.closeEditorWarningMessage,
        closeEditorWarningConfirmBtn: l10n.closeEditorWarningConfirmBtn,
        closeEditorWarningCancelBtn: l10n.cancel,
      ),
      cropRotateEditor: I18nCropRotateEditor(
        bottomNavigationBarText: l10n.cropImage,
        rotate: l10n.rotate,
        flip: l10n.flip,
        ratio: l10n.ratio,
        back: l10n.back,
        cancel: l10n.cancel,
        done: l10n.done,
        reset: l10n.reset,
        undo: l10n.undo,
        redo: l10n.redo,
      ),
      tuneEditor: I18nTuneEditor(
        bottomNavigationBarText: l10n.tuneTool,
        back: l10n.back,
        done: l10n.done,
        undo: l10n.undo,
        redo: l10n.redo,
        brightness: l10n.brightness,
        contrast: l10n.contrast,
        saturation: l10n.saturation,
        exposure: l10n.exposure,
        hue: l10n.hue,
        temperature: l10n.temperature,
        sharpness: l10n.sharpness,
        fade: l10n.fade,
      ),
      paintEditor: I18nPaintEditor(
        bottomNavigationBarText: l10n.paintTool,
        moveAndZoom: l10n.moveAndZoom,
        freestyle: l10n.freestyle,
        arrow: l10n.arrow,
        line: l10n.line,
        rectangle: l10n.rectangle,
        circle: l10n.circle,
        eraser: l10n.eraser,
        lineWidth: l10n.lineWidth,
        strokeWidth: l10n.strokeWidth,
        toggleFill: l10n.toggleFill,
        changeOpacity: l10n.changeOpacity,
        opacity: l10n.opacity,
        color: l10n.color,
        fill: l10n.fill,
        cancel: l10n.cancel,
        undo: l10n.undo,
        redo: l10n.redo,
        done: l10n.done,
        back: l10n.back,
      ),
      filterEditor: I18nFilterEditor(
        bottomNavigationBarText: l10n.filterTool,
        back: l10n.back,
        done: l10n.done,
        filters: I18nFilters(none: l10n.none),
      ),
      textEditor: I18nTextEditor(
        bottomNavigationBarText: l10n.textTool,
        inputHintText: l10n.inputHintText,
        done: l10n.done,
        back: l10n.back,
        textAlign: l10n.textAlign,
        fontScale: l10n.fontScale,
        backgroundMode: l10n.backgroundMode,
      ),
      blurEditor: I18nBlurEditor(
        bottomNavigationBarText: l10n.blurTool,
        back: l10n.back,
        done: l10n.done,
      ),
      emojiEditor: I18nEmojiEditor(
        bottomNavigationBarText: l10n.emojiTool,
        search: l10n.search,
      ),
      layerInteraction: I18nLayerInteraction(
        remove: l10n.remove,
        edit: l10n.edit,
      ),
      stickerEditor: I18nStickerEditor(
        bottomNavigationBarText: l10n.stickerTool,
      ),
    );
